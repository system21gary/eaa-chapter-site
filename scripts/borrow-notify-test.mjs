/**
 * Drives one real borrow request through the site, to confirm the tool's owner
 * is notified by email.
 *
 *   node scripts/borrow-notify-test.mjs
 *
 * Uses a seeded fictional member as the borrower (setting a throwaway password
 * on that demo account) and requests a tool the admin owns, so the notification
 * goes to a real address that can be checked. Cleans the request up afterwards.
 *
 * Development only -- it writes to the members' database.
 */
import * as Users from '../src/models/users.js';
import { get, run } from '../src/db/index.js';
import config from '../src/config.js';

const BASE = (process.env.BASE_URL || 'http://localhost:3000').replace(/\/+$/, '');
const PREFIX = new URL(BASE).pathname.replace(/\/+$/, '');
const TEMP_PASSWORD = 'borrow-notify-test-passphrase-42';

let cookie = '';

async function req(path, { method = 'GET', body = null } = {}) {
  const headers = { cookie };
  let payload;
  if (body) {
    headers['content-type'] = 'application/x-www-form-urlencoded';
    headers.origin = BASE.replace(PREFIX, '') || BASE;
    payload = new URLSearchParams(body).toString();
  }
  const res = await fetch(`${BASE}${path}`, { method, headers, body: payload, redirect: 'manual' });
  for (const c of res.headers.getSetCookie?.() ?? []) {
    const pair = c.split(';')[0];
    if (pair.startsWith('eaa1699.sid=')) cookie = pair;
  }
  const text = res.headers.get('content-type')?.includes('text') ? await res.text() : '';
  return { status: res.status, text };
}

const csrf = (html) => html.match(/name="_csrf" value="([^"]+)"/)?.[1];

/* The tool and the two people involved. */
const tool = get('SELECT id, name, owner_id FROM tools WHERE owner_id = 1 LIMIT 1');
if (!tool) throw new Error('no tool owned by the admin to test with');
const owner = Users.findById(tool.owner_id);
const borrower = get(
  "SELECT id, email, first_name FROM users WHERE id <> ? AND status = 'active' LIMIT 1",
  [owner.id]
);

console.log(`\nTool:     ${tool.name} (#${tool.id})`);
console.log(`Owner:    ${owner.first_name} <${owner.email}>`);
console.log(`Borrower: ${borrower.first_name} (seeded demo member)`);
console.log(`Mail:     ${config.mail.transport}\n`);

// A throwaway password on a fictional account, so the request goes through the
// real route with a real session rather than being faked at the model layer.
await Users.setPassword(borrower.id, TEMP_PASSWORD);

const login = await req('/login');
const signedIn = await req('/login', {
  method: 'POST',
  body: { _csrf: csrf(login.text), email: borrower.email, password: TEMP_PASSWORD },
});
console.log(signedIn.status === 302 ? '  signed in as the borrower' : `  FAILED to sign in (${signedIn.status})`);

const toolPage = await req(`/members/locker/${tool.id}`);
const from = new Date(Date.now() + 3 * 86400000).toISOString().slice(0, 16);
const to = new Date(Date.now() + 6 * 86400000).toISOString().slice(0, 16);

const before = get('SELECT COUNT(*) AS n FROM email_outbox').n;
const asked = await req(`/members/locker/${tool.id}/borrow`, {
  method: 'POST',
  body: {
    _csrf: csrf(toolPage.text),
    message:
      'Testing the borrow notification: does the owner get an email? ' +
      'Safe to decline — this was generated by a script.',
    needed_from: from,
    needed_to: to,
  },
});
console.log(asked.status === 302 ? '  borrow request submitted' : `  FAILED to submit (${asked.status})`);

// Give the background worker its moment.
await new Promise((r) => setTimeout(r, 4000));

const after = get('SELECT COUNT(*) AS n FROM email_outbox').n;
const mail = get(
  `SELECT id, to_addr, subject, sent_at, error, body_text
     FROM email_outbox ORDER BY id DESC LIMIT 1`
);

console.log(`\n  outbox grew by ${after - before}`);
console.log(`  message #${mail.id} to ${mail.to_addr}`);
console.log(`  subject: ${mail.subject}`);
console.log(`  status:  ${mail.sent_at ? 'DELIVERED ' + mail.sent_at : mail.error || 'queued'}`);
console.log('\n──── what the owner receives ────');
console.log(mail.body_text);
console.log('─────────────────────────────────');

/* Leave nothing behind: the request, and the demo member's password. */
const request = get(
  'SELECT id FROM borrow_requests WHERE tool_id = ? AND requester_id = ? ORDER BY id DESC LIMIT 1',
  [tool.id, borrower.id]
);
if (request) run('DELETE FROM borrow_requests WHERE id = ?', [request.id]);
run('UPDATE users SET password_hash = NULL WHERE id = ?', [borrower.id]);
console.log('\n  cleaned up: request deleted, demo member has no password again\n');
